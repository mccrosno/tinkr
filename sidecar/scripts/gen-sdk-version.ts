// Writes src/sdkVersion.generated.ts from the installed Agent SDK's package.json.
// The SDK doesn't export its package.json, so we read it from disk at dev time and
// commit the result. test/sdkVersion.test.ts fails if this file goes stale.
// Run after upgrading the SDK: bun run gen

import { dirname, join } from 'node:path'

export async function readInstalledSdk() {
  // Resolve the SDK's entry file, then read package.json next to it.
  const entry = Bun.resolveSync('@anthropic-ai/claude-agent-sdk', import.meta.dir)
  const pkg = await Bun.file(join(dirname(entry), 'package.json')).json()
  return { sdkVersion: pkg.version as string, claudeCodeVersion: pkg.claudeCodeVersion as string }
}

export function render(v: { sdkVersion: string; claudeCodeVersion: string }) {
  return `// Generated by scripts/gen-sdk-version.ts. Do not edit; run \`bun run gen\` after upgrading the SDK.

/** Version of @anthropic-ai/claude-agent-sdk this sidecar was built against. */
export const SDK_VERSION = '${v.sdkVersion}'

/**
 * The Claude Code CLI version bundled with that SDK. The SDK expects a CLI at least
 * this new when it's given a CLI path, so it's Tinkr's minimum supported version.
 */
export const MIN_CLI_VERSION = '${v.claudeCodeVersion}'
`
}

if (import.meta.main) {
  const out = join(import.meta.dir, '..', 'src', 'sdkVersion.generated.ts')
  await Bun.write(out, render(await readInstalledSdk()))
  console.log('wrote', out)
}
