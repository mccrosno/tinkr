// Conversation history: Claude Code stores every chat as a transcript, per working
// folder. These helpers list those chats and turn a transcript back into the rows the
// chat shows. The conversion is pure (it takes the SDK's messages as input), so it's
// unit-tested without running Claude.

import { deleteSession, getSessionMessages, listSessions, renameSession, type SDKSessionInfo, type SessionMessage } from '@anthropic-ai/claude-agent-sdk'
import type { AttachmentPreview, ChatSummary, HistoryItem } from '../../shared/protocol'
import { resolve } from 'node:path'
import { describeTool } from './tools'

/** Longest title shown in the list; longer first prompts are cut. */
const MAX_TITLE = 80

/**
 * A chat's title: the name the user gave it, else its first prompt. (The SDK's
 * `summary` falls back to the *latest* prompt, which makes a poor title.)
 */
export function chatTitle(info: Pick<SDKSessionInfo, 'customTitle' | 'firstPrompt' | 'summary'>): string {
  if (info.customTitle?.trim()) return info.customTitle.trim()
  const prompt = stripSelections(info.firstPrompt ?? info.summary ?? '').replace(/\s+/g, ' ').trim()
  if (!prompt) return 'Untitled chat'
  return prompt.length > MAX_TITLE ? prompt.slice(0, MAX_TITLE - 1) + '…' : prompt
}

/** Drop Tinkr's <selection> blocks from a prompt, leaving what the user typed. */
function stripSelections(text: string) {
  return text.replace(/<selection\b[^>]*>[\s\S]*?<\/selection>/g, '')
}

/** `folder` is the chat's folder as the protocol says it: null for the home folder. */
export function toSummary(info: SDKSessionInfo, folder: string | null): ChatSummary {
  return { sessionId: info.sessionId, title: chatTitle(info), folder, lastModified: info.lastModified }
}

/** Is `a` the same folder as `b`? Case-insensitive on Windows; trailing slashes don't count. */
export function sameFolder(a: string, b: string, windows = process.platform === 'win32') {
  const norm = (p: string) => {
    const r = resolve(p)
    return windows ? r.toLowerCase() : r
  }
  return norm(a) === norm(b)
}

/**
 * User messages Claude Code writes itself rather than the user typing them: notes about
 * an interrupted turn, and the CLI's slash-command bookkeeping (in chats started there).
 */
function isBookkeeping(text: string) {
  const t = text.trimStart()
  return (
    t.startsWith('[Request interrupted by user') ||
    t.startsWith('<command-name>') ||
    t.startsWith('<command-message>') ||
    t.startsWith('<local-command-') ||
    t.startsWith('Caveat: The messages below were generated by the user while running local commands')
  )
}

/** A content block, loosely typed: transcripts can hold any Messages API block. */
interface Block {
  type: string
  text?: string
  id?: string
  name?: string
  input?: unknown
  tool_use_id?: string
  is_error?: boolean
  title?: string
  source?: { type?: string; media_type?: string; data?: string }
}

/** A message's content as a list of blocks (it's stored as a plain string sometimes). */
function blocksOf(message: unknown): Block[] {
  const content = (message as { content?: unknown } | null)?.content
  if (typeof content === 'string') return [{ type: 'text', text: content }]
  return Array.isArray(content) ? content.filter((b): b is Block => !!b && typeof b === 'object' && typeof b.type === 'string') : []
}

/** What to show for an image or document the user attached. */
function previewOf(block: Block, index: number): AttachmentPreview | null {
  const src = block.source ?? {}
  if (block.type === 'image') {
    const mediaType = src.media_type ?? 'image/png'
    return {
      name: block.title ?? `image-${index + 1}.${mediaType.split('/')[1] ?? 'png'}`,
      mediaType,
      ...(src.type === 'base64' && src.data ? { data: src.data } : {}),
    }
  }
  if (block.type === 'document') {
    return { name: block.title ?? `document-${index + 1}`, mediaType: src.media_type ?? 'application/octet-stream' }
  }
  return null
}

/**
 * Turn a transcript into chat rows: what the user wrote (with their attachments),
 * Claude's text, and its tool calls with whether they failed. Sub-agent messages and
 * thinking are left out, as they are in a live chat.
 */
export function toHistory(messages: SessionMessage[], cwd?: string): HistoryItem[] {
  const items: HistoryItem[] = []
  const tools = new Map<string, Extract<HistoryItem, { kind: 'tool' }>>()

  for (const m of messages) {
    if (m.parent_tool_use_id !== null) continue // a sub-agent's work
    const blocks = blocksOf(m.message)

    if (m.type === 'user') {
      // Tool results come back as "user" messages: they only update the tool's row.
      for (const b of blocks) {
        if (b.type !== 'tool_result' || !b.tool_use_id) continue
        const tool = tools.get(b.tool_use_id)
        if (tool) tool.isError = b.is_error === true
      }
      const text = blocks
        .filter((b) => b.type === 'text' && typeof b.text === 'string')
        .map((b) => b.text)
        .join('\n\n')
      const attachments = blocks.map(previewOf).filter((a): a is AttachmentPreview => a !== null)
      if ((!text.trim() || isBookkeeping(text)) && !attachments.length) continue
      items.push({ kind: 'user', text: isBookkeeping(text) ? '' : text, attachments })
    } else if (m.type === 'assistant') {
      for (const b of blocks) {
        if (b.type === 'text' && b.text?.trim()) {
          // Claude Code stores one block per message; join consecutive text into one row.
          const last = items.at(-1)
          if (last?.kind === 'assistant') last.text += '\n\n' + b.text
          else items.push({ kind: 'assistant', text: b.text })
        } else if (b.type === 'tool_use' && b.id && b.name) {
          const tool = { kind: 'tool' as const, toolUseId: b.id, name: b.name, summary: describeTool(b.name, b.input, cwd), isError: false }
          tools.set(b.id, tool)
          items.push(tool)
        }
      }
    }
  }
  return items
}

// ---------------------------------------------------------------------------
// Reading and changing Claude Code's stored chats. `dir` is the chat's working folder
// (the project, or Tinkr's chats folder); sessions are stored per folder.
// ---------------------------------------------------------------------------

/**
 * The chats in `dir` (null = all folders), newest first. Includes chats started in the
 * Claude Code CLI and Desktop's Code tab, which store sessions in the same place.
 * `home` is the folder that stands for "no folder" (the home folder).
 */
export async function listChats(dir: string | null, home: string): Promise<ChatSummary[]> {
  const sessions = await listSessions(dir ? { dir } : {})
  const folderOf = (s: SDKSessionInfo): string | null => {
    const cwd = dir ?? s.cwd ?? home
    return sameFolder(cwd, home) ? null : cwd
  }
  return sessions
    .filter((s) => !s.archived)
    .sort((a, b) => b.lastModified - a.lastModified)
    .map((s) => toSummary(s, folderOf(s)))
}

export async function loadChat(sessionId: string, dir: string, project?: string): Promise<HistoryItem[]> {
  return toHistory(await getSessionMessages(sessionId, { dir }), project)
}

export async function renameChat(sessionId: string, title: string, dir: string) {
  const t = title.trim()
  if (!t) throw new Error('a chat needs a name')
  await renameSession(sessionId, t, { dir })
}

export async function deleteChat(sessionId: string, dir: string) {
  await deleteSession(sessionId, { dir })
}
